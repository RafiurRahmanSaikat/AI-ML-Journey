from io import BytesIO
from django.http import HttpResponse
from reportlab.lib.pagesizes import A4, landscape
from reportlab.pdfgen import canvas
from rest_framework.views import APIView
from rest_framework.permissions import IsAuthenticated
from rest_framework.exceptions import ValidationError
from apps.core.permissions import AdminOrHeadmaster
from apps.students.models import Student
class StudentCardView(APIView):
    permission_classes=[AdminOrHeadmaster]
    def get(self, request, student_id):
        try: student=Student.objects.select_related("school_class","section").get(pk=student_id)
        except Student.DoesNotExist: raise ValidationError({"student_id":"Student not found."})
        kind=request.query_params.get("kind","ID").upper()
        allowed={"ID","ADMINISTRATION","REGISTRATION","TRANSFER","TESTIMONIAL"}
        if kind not in allowed: raise ValidationError({"kind":f"Choose one of {', '.join(sorted(allowed))}."})
        buf=BytesIO(); page=landscape(A4) if kind in {"ID","REGISTRATION"} else A4
        c=canvas.Canvas(buf,pagesize=page); w,h=page
        c.setTitle(f"{kind} - {student.name}")
        c.setFont("Helvetica-Bold",18); c.drawCentredString(w/2,h-55,"SCHOOL MANAGEMENT SYSTEM")
        c.setFont("Helvetica-Bold",14); c.drawCentredString(w/2,h-82,kind.replace("_"," ")+" CARD")
        c.setLineWidth(1); c.rect(35,35,w-70,h-100)
        lines=[("Name",student.name),("Admission No.",student.admission_no),("Roll",student.roll or "-"),
          ("Class",student.school_class.name),("Section",student.section.name),("Group",student.get_group_display()),
          ("Date of Birth",student.date_of_birth or "-"),("Father",student.father_name or "-"),("Mother",student.mother_name or "-"),
          ("Phone",student.phone or "-"),("Address",student.address or "-")]
        y=h-125
        c.setFont("Helvetica",11)
        for label,value in lines:
            c.setFont("Helvetica-Bold",10); c.drawString(55,y,str(label)+":")
            c.setFont("Helvetica",10); c.drawString(165,y,str(value)[:100]); y-=24
            if y<55: c.showPage(); y=h-60
        c.setFont("Helvetica-Oblique",8); c.drawString(55,48,"Generated by School Management API. Verify official details before use.")
        c.save(); buf.seek(0)
        resp=HttpResponse(buf.getvalue(),content_type="application/pdf")
        resp["Content-Disposition"]=f'attachment; filename="{kind.lower()}-{student.admission_no}.pdf"'
        return resp
